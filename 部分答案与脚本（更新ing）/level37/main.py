def rotr(x, n):
    return ((x >> n) | (x << (32 - n))) & 0xFFFFFFFF

def sha256_custom_iv(data, iv):
    bit_len = len(data) * 8
    data += b'\x80'
    while len(data) % 64 != 56:
        data += b'\x00'
